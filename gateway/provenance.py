"""Where a run's data came from, told the same way on every page.

Each kind of input says what made it:
  - a Synthea feed carries source.json (written by scripts/generate_population.py): generator,
    release, seed, patients; a faulted copy keeps it and adds faults.json (scripts/inject_faults.py);
  - the built-in examples are fixtures/ (written by scripts/make_fixtures.py from a fixed seed).

describe() reads that for a run's inputs (the pipeline stores it in the report); html() turns it
into the "Where this data comes from" table the Results, Inspector and Monitor pages show. The
table's wording is fixed here and checked against the generators by tests/unit/test_provenance.py,
so it cannot drift from what the scripts actually do.
"""

from __future__ import annotations

import html as _html
import json
from pathlib import Path

MANIFEST = "source.json"
ROOT = Path(__file__).resolve().parents[1]
FIXTURE_SEED = 20261019          # scripts/make_fixtures.py SEED (a test keeps them equal)
QLD_SUBURBS_FEED = 26            # scripts/synthea_to_hl7.py QLD_SUBURBS (a test keeps them equal)
QLD_SUBURBS_EXAMPLES = 5         # scripts/make_fixtures.py SUBURBS (a test keeps them equal)
SYNTHEA_URL = "https://github.com/synthetichealth/synthea"


def feed_manifest(release: str, seed: int, state: str, patients: int) -> dict:
    """What scripts/generate_population.py writes next to a generated feed."""
    return {"kind": "synthea", "generator": "Synthea", "release": release, "seed": seed,
            "state": state, "patients": patients, "localised_to": "Queensland",
            "suburbs": QLD_SUBURBS_FEED, "exporter": "scripts/synthea_to_hl7.py"}


def _hl7_files(path: Path) -> int:
    return sum(1 for _ in path.rglob("*.hl7")) if path.is_dir() else int(path.suffix == ".hl7")


def describe(inputs: list[Path]) -> list[dict]:
    """One entry per input: what made it, from the files beside it (never assumed)."""
    out = []
    for raw in inputs:
        path = Path(raw)
        folder = path if path.is_dir() else path.parent
        shown = path.as_posix()
        try:
            shown = path.resolve().relative_to(ROOT).as_posix()
        except ValueError:
            pass
        manifest = folder / MANIFEST
        if manifest.is_file():
            entry = json.loads(manifest.read_text()) | {"path": shown}
            ledger = folder / "faults.json"
            if ledger.is_file():
                faults = json.loads(ledger.read_text())
                entry["planted"] = faults.get("faulted_messages", len(faults.get("faults", [])))
                entry["fault_seed"] = faults.get("seed")
            out.append(entry)
        elif "fixtures" in path.resolve().parts:
            out.append({"kind": "examples", "path": shown, "files": _hl7_files(path), "seed": FIXTURE_SEED,
                        "suburbs": QLD_SUBURBS_EXAMPLES, "made_by": "scripts/make_fixtures.py"})
        else:
            out.append({"kind": "unknown", "path": shown, "files": _hl7_files(path)})
    return out


def _e(text) -> str:
    return _html.escape(str(text), quote=True)


def _n(n) -> str:
    return f"{int(n):,}"


# The "Real or made up" column: words, not colour, carry the meaning.
INVENTED, PLACE, NUMBER = "Made up", "Real place name", "Random number"


def rows(sources: list[dict]) -> list[tuple[str, str, str]]:
    """(detail, where it comes from, real or made up), only for the kinds of data present. Where
    a page has both kinds, 'where' reads "Population: ... Examples: ..." (one line each on the page)."""
    kinds = {s["kind"] for s in sources}
    syn, ex = "synthea" in kinds, "examples" in kinds
    both = syn and ex

    def pick(feed: str, examples: str) -> str:
        if both:
            return f"Population: {feed} Examples: {examples}"
        text = feed if syn else examples
        return text[:1].upper() + text[1:]

    out = [
        ("Names", pick("random first and last names from Synthea (the numbers it adds to keep names "
                       "unique are removed).", "a short fixed list of common names, such as CITIZEN or CHEN."),
         INVENTED),
        ("Date of birth and sex", pick("generated by Synthea's simulation.", "random, from a fixed seed."), INVENTED),
        ("Street address", pick("Synthea's invented street names.",
                                "a few generic street names, such as Smith St, that may exist somewhere "
                                "but are not anyone's address here."), INVENTED),
        ("Suburb, postcode and state",
         f"Real Queensland place names and postcodes (public information), picked at random from a list of "
         f"{_n(QLD_SUBURBS_FEED) if syn else _n(QLD_SUBURBS_EXAMPLES)}"
         f"{f' ({_n(QLD_SUBURBS_EXAMPLES)} for the examples)' if both else ''}. No real person is attached to them.",
         PLACE),
        ("IHI, Medicare number and MRN",
         "Random digits with a correct check digit, so they pass the format rules. Real numbers come from the "
         "same ranges, so one can match a real person's number by chance; here it is only ever paired with "
         "made-up details, so it says nothing about that person.", NUMBER),
        ("Test results", pick("simulated by Synthea, with its test codes (LOINC) and units kept exactly as "
                              "generated.", "fixed sample values written into the example generator."), INVENTED),
        ("Lab and hospital names", "DEMOLAB, DEMOLAB2, QLDDEMO and QLDDEMO2 are placeholders, not real organisations.", INVENTED),
    ]
    if any(s.get("planted") for s in sources):
        out.append(("Mistakes", "Planted on purpose by the project's fault injector, which keeps a list of every "
                                "change it made.", INVENTED))
    return out


def summary(sources: list[dict]) -> str:
    """One sentence: what this page's data actually is, from the run's own inputs."""
    phrases = []
    for s in sources:
        if s["kind"] == "synthea":
            p = (f"a synthetic population of {_n(s['patients'])} patients made by "
                 f'<a href="{SYNTHEA_URL}">Synthea</a> {_e(s["release"])} (seed {_e(s["seed"])})')
            if s.get("slice"):          # a page that shows only part of the feed says so
                sl = s["slice"]
                p = (f"{_n(sl['messages'])} messages from {p}"
                     + (f", {_n(sl['planted'])} of them with a mistake planted on purpose" if sl.get("planted") else ""))
            elif s.get("planted"):
                p += f", with {_n(s['planted'])} mistakes planted on purpose"
            phrases.append(p)
        elif s["kind"] != "examples":
            phrases.append(f"{_n(s['files'])} {'file' if s['files'] == 1 else 'files'} from "
                           f"<code>{_e(s['path'])}</code>, whose origin this run did not record")
    examples = sum(s["files"] for s in sources if s["kind"] == "examples")
    if examples:     # the example folders (fixtures/golden, fixtures/faults) read as one set
        phrases.append(f"{_n(examples)} example {'file' if examples == 1 else 'files'} written by the "
                       f"project's own generator (seed {_e(FIXTURE_SEED)})")
    return ("This page uses " + ", and ".join(phrases) + ".") if phrases else ""


def _where(text: str) -> str:
    """"Population: a. Examples: b." -> one labelled line each."""
    if text.startswith("Population: ") and " Examples: " in text:
        feed, examples = text[len("Population: "):].split(" Examples: ", 1)
        return (f'<span class="who">Population</span> {_e(feed)}<br>'
                f'<span class="who">Examples</span> {_e(examples)}')
    return _e(text)


def html(sources: list[dict]) -> str:
    """The inner HTML of a page's "Where this data comes from" section (site classes)."""
    known = [s for s in sources if s["kind"] in ("synthea", "examples")]
    table = "".join(
        f"<tr><th scope=\"row\">{_e(d)}</th><td>{_where(where)}</td><td><span class=\"origin\">{_e(real)}</span></td></tr>"
        for d, where, real in rows(known)) if known else ""
    regenerated = any(s["kind"] == "synthea" for s in sources)
    return (
        '<div class="prov-head"><h2 id="data-h">Where this data comes from</h2>'
        "<p>Every patient here is made up. Nothing comes from real health records, de-identified or "
        "otherwise, and no sign-up or licence with personal information was needed to make it.</p>"
        f"<p>{summary(sources)}</p></div>"
        + (f'<div class="prov-table"><table><thead><tr><th scope="col">Detail</th><th scope="col">Where it comes from</th>'
           f'<th scope="col">Real or made up</th></tr></thead><tbody>{table}</tbody></table></div>' if table else "")
        + ("<p class=\"prov-foot\">The generated population is not stored in the project; its automated checks "
           "rebuild it from the same pinned version and seed, so anyone can reproduce it exactly.</p>"
           if regenerated else "")
    )


