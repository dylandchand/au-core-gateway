"""Write docs/RUNBOOK.md: what to do when the interface misbehaves, one entry per fault the
Interface Monitor can stage.

Generated, never edited by hand: each fault's description and checks come from
gateway/monitor/build.py (the same text the page shows), and every reply quoted is what the
gateway's own code answers today, from a fresh session with a fixed clock. A test fails if the
file is out of date: run this script after changing a fault or the gateway's answers.

Usage:  python scripts/make_runbook.py            (writes docs/RUNBOOK.md)
        python scripts/make_runbook.py --check    (exit 1 if docs/RUNBOOK.md is out of date)
"""

from __future__ import annotations

import re
import sys
import tempfile
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from gateway.interface.mllp import split_messages  # noqa: E402
from gateway.interface.session import MAX_HELD, MAX_SEEN, Session  # noqa: E402
from gateway.monitor import build  # noqa: E402

OUT = ROOT / "docs" / "RUNBOOK.md"
CLOCK = datetime(2026, 10, 19, 9, 0, tzinfo=timezone(timedelta(hours=10)))
GOLDEN = ROOT / "fixtures" / "golden"


def _what(text: str) -> str:
    """The fault's description without the Monitor-only notes on where its example comes from."""
    keep = [x for x in re.split(r"(?<=\.) ", text) if not x.startswith(("Uses ", "Made from "))]
    return " ".join(keep)


def _reply(r: dict) -> str:
    return f"`{r['code']}` {r['text']}"


def _answers(sc: dict, work: Path) -> list[str]:
    """What the gateway answers when the fault happens, from its own code."""
    regs = split_messages((GOLDEN / "clean-patients.hl7").read_text())
    s = Session(work, clock=lambda: CLOCK)
    if sc["kind"] == "network":
        return ["Nothing: no complete message reaches the gateway, so no acknowledgement is sent."]
    if sc["id"] == "early":           # a report for the first example patient, before her registration
        lab = split_messages((GOLDEN / "lab-results.hl7").read_text())[0]
        first, reg = s.receive(lab), s.receive(regs[0])
        [filed] = reg["released"]
        return [f"The report: {_reply(first)}", f"Its registration: {_reply(reg)}",
                f"Then the held report is filed: {_reply(filed)} (no second acknowledgement)"]
    for reg in regs:                  # the example patients are registered first, as in the feed
        s.receive(reg)
    first = s.receive(sc["text"])
    if sc.get("then"):
        again = s.receive(sc["then"])
        return [f"The first copy: {_reply(first)}", f"The second copy: {_reply(again)}"]
    return [_reply(first)]


INTRO = f"""# Interface support runbook

What to do when the lab interface misbehaves: one entry for each fault the
[Interface Monitor](https://dylandchand.github.io/au-core-gateway/monitor/) can stage, with what you
see, what the gateway answers, and the checks to work through in order. It applies to the Monitor
and to the local listener (`python -m gateway listen`). Everything here uses synthetic data only.

This file is generated by `scripts/make_runbook.py` from the faults in `gateway/monitor/build.py`,
and every reply quoted is what the gateway's own code answers. Do not edit it by hand.

## Reading an acknowledgement

Every message is answered with an HL7 acknowledgement (ACK). Its `MSA` segment carries the code
and a short reason.

| Code | Means | What to do |
| --- | --- | --- |
| `AA` | Accepted: read and checked, no errors by the gateway's own checks | Nothing, unless it carries warnings |
| `AE` | Error: read, but the gateway's checks found a problem (the reason names the first, and its HL7 field) | Follow the fault's entry below |
| `AR` | Rejected: unreadable, not UTF-8, or a message type this interface does not handle | Check the sender's set-up |
| no ACK | Nothing complete arrived | Check the connection (see the network faults) |

An `AA` means received and read, not that every value is right: the official AU Core validator runs
separately (see "Accepted, but still wrong").

Field locations read as HL7 does: `PID-3` is field 3 of the patient line, `OBX(2)-5` is field 5 of
the second result line.

## First checks, for any incident

1. **Is anything arriving?** Check when the last message came in (the Monitor's "Last message", or
   the listener's log).
2. **One sender or all of them?** One points at that system; all points at the network or the
   gateway.
3. **What did the gateway answer?** Read the ACK code and reason, and find the field it names.
4. **Is it waiting?** A lab report for a patient not registered yet is held, and filed by itself when
   the registration arrives (queue limit: {MAX_HELD:,}).
5. **Was it sent twice?** A resend of the same message is answered as a duplicate and processed
   once (the gateway remembers the last {MAX_SEEN:,} messages).
6. **Record it.** Log the incident with the control IDs (`MSH-10`) affected, what you saw and what
   you did.

Escalate early when results for patients are delayed. Problems in the data are fixed at the source:
raise them with the sending lab, never patch them in the gateway.
"""

TAIL = """## Useful commands

```sh
python -m gateway listen --state out/interface-state.json   # waits on 127.0.0.1:2575; keeps what it knows across restarts
python -m gateway send fixtures/golden                      # sends files, prints each MSA line
```

The state file is JSON: `registered` (accepted registrations), `held` (lab reports waiting for their
patient, with `held_since`) and `seen` (the messages already answered, for spotting resends).

## Recording an incident

- When it started, and when it was noticed
- Which sender, and the control IDs (`MSH-10`) affected
- The ACK codes and reasons the gateway sent
- What was checked, what was found, and who was contacted
- How it was resolved, and whether anything needs a change request
"""


def render() -> str:
    parts = [INTRO]
    faults = build.scenarios(describe_only=True)
    for group, title in (("send", "Problems in a message"), ("network", "Problems on the network")):
        parts.append(f"## {title}\n")
        with tempfile.TemporaryDirectory() as tmp:
            for k, sc in enumerate(f for f in faults if f["kind"] == group):
                answers = _answers(sc, Path(tmp) / str(k))
                simulated = " (simulated on the Monitor)" if group == "network" else ""
                parts.append(f"### {sc['title']}{simulated}\n\n{_what(sc['what'])}\n\n**Where to look:** {sc['short']}.\n\n"
                             + "**The gateway answers:**\n\n" + "".join(f"- {a}\n" for a in answers)
                             + "\n**Checks, in order:**\n\n" + "".join(f"{n}. {step}\n" for n, step in enumerate(sc["steps"], 1)))
    parts.append(TAIL)
    return "\n".join(parts)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("docs/RUNBOOK.md is out of date: run python scripts/make_runbook.py")
            return 1
        print("docs/RUNBOOK.md is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
